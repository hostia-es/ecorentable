## Preguntas Frecuentes (FAQs)

### ¿Es peligrosa la descarbonización para el motor?
No, siempre que se utilice maquinaria profesional como la gama H2 Profit. El hidrógeno no es corrosivo. Al ser una limpieza por pirólisis, los residuos salen en estado gaseoso, evitando daños mecánicos.

### ¿Cada cuánto tiempo se debe realizar?
Recomendamos una descarbonización cada **15.000 o 20.000 kilómetros**, o una vez al año, coincidiendo con el mantenimiento de aceite y filtros.

### ¿Sirve para motores gasolina y diésel?
Sí, es igualmente efectiva en ambos. En diésel es crítica por la generación de hollín; en gasolina de inyección directa, ayuda a limpiar las válvulas de admisión.

### ¿Cuánto dura el proceso?
Entre **60 y 90 minutos**, sin necesidad de desmontar piezas.

### ¿Puedo notar los resultados inmediatamente?
Sí, especialmente en vehículos con más de 80.000 km: respuesta más ágil, menos ruido al ralentí y desaparición del humo negro.

