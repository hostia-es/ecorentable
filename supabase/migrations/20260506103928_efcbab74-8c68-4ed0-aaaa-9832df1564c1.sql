## ¿Qué es exactamente la carbonilla y por qué se produce?

La carbonilla es un residuo sólido compuesto principalmente por hidrocarburos no quemados y depósitos metálicos que se cristalizan debido a las altas temperaturas en el interior del cilindro. Aunque los motores modernos son más eficientes, están sujetos a normativas de emisiones muy estrictas que han forzado la implementación de sistemas como la **EGR (Recirculación de Gases de Escape)** y los **Filtros de Partículas (DPF/FAP)**.

Estos sistemas, si bien son beneficiosos para el medio ambiente, favorecen la acumulación de residuos si el vehículo no alcanza temperaturas de funcionamiento óptimas (muy común en trayectos urbanos cortos). El resultado es una "asfixia" progresiva del bloque motor.

### Factores que aceleran la creación de depósitos
1.  **Conducción urbana:** Bajas revoluciones y constantes paradas impiden que el motor se autolimpie por temperatura.
2.  **Calidad del combustible:** Combustibles con aditivos deficientes generan más residuos durante la explosión.
3.  **Mantenimiento deficiente:** Filtros de aire sucios o aceite degradado alteran la mezcla estequiométrica (aire-combustible).

