## ¿Qué es exactamente el filtro de partículas y por qué se obstruye?

El DPF/FAP es una estructura cerámica de carburo de silicio, con forma de panal, situada en el tramo de escape. Su función es filtrar físicamente las partículas de carbonilla. Para "limpiarse" a sí mismo, el coche realiza **regeneraciones**: inyecta más combustible para elevar la temperatura de los gases de escape hasta los 600°C y quemar ese hollín.

El problema surge cuando el vehículo realiza trayectos cortos urbanos. El motor no alcanza la temperatura óptima, la regeneración se interrumpe y el filtro se satura de forma irreversible. A continuación, detallamos los 7 síntomas inequívocos de este proceso.

---

## 1. El testigo de fallo de motor o filtro en el cuadro
Es el síntoma más evidente y, a menudo, el último paso antes de una avería grave. Dependiendo del fabricante, puede aparecer un icono con forma de escape con puntos en su interior o, simplemente, el testigo de **"Check Engine"**.

En vehículos modernos equipados con sistemas de diagnosis avanzada, el software detectará una **diferencia de presión excesiva** entre la entrada y la salida del filtro a través del sensor de presión diferencial. Si este sensor detecta que el gas no fluye, enviará una señal a la centralita (ECU) para alertar al conductor.

## 2. Activación del modo de "Limp Mode" o protección
Cuando la obstrucción alcanza niveles peligrosos (generalmente por encima del 70-80% de saturación), la ECU activa el **modo de emergencia**. Los síntomas son:
*   Limitación drástica de las revoluciones (normalmente no sube de 2.500 rpm).
*   Desactivación del turbo.
*   Pérdida de potencia inmediata.

Este es un mecanismo de defensa para evitar que la contrapresión de los gases de escape dañe las válvulas de escape o el propio turbocompresor.

## 3. Incremento notable en el consumo de combustible
Un filtro obstruido es como intentar correr con una máscara que no permite exhalar. El motor debe realizar un sobreesfuerzo para expulsar los gases, lo que eleva el consumo.

Además, si el filtro está al límite, la centralita intentará forzar **regeneraciones activas** constantemente. Para ello, realiza post-inyecciones de combustible que no se usan para mover el vehículo, sino para calendar el escape, lo que se traduce en un aumento del gasto de gasoil de hasta un 15-20% sin que el conductor note una mejora en el rendimiento.

## 4. Olor a quemado y humo denso por el escape
Si percibes un olor acre, similar a metal de soldadura o goma quemada al detener el coche, es probable que el sistema esté intentando una regeneración desesperada.

En cuanto al humo, aunque el DPF está diseñado para eliminar el humo negro (carbonilla), si la cerámica interna se ha agrietado por el exceso de calor o la presión, el coche empezará a emitir **humo negro** en aceleraciones. Si el humo es **blanco o azulado**, puede indicar que el combustible de las regeneraciones fallidas está pasando al cárter o que el filtro está colmatado de aceite.

## 5. Subida del nivel de aceite en el cárter (Peligro crítico)
Este es uno de los síntomas más técnicos y peligrosos. Cuando las regeneraciones se interrumpen repetidamente, el gasoil inyectado en la fase de expansión no se quema y resbala por las paredes del cilindro hasta el cárter derterminando la **dilución del aceite**.

