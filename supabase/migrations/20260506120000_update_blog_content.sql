## 6. Respuesta tardía del motor y tirones
Un sistema de escape restringido afecta directamente al ciclo de admisión. El motor "no respira". Notarás que, al pisar el acelerador, el coche tarda varios segundos en reaccionar (lag) o que el motor funciona de forma errática a ralentí, con vibraciones que antes no existían.

## 7. Aumento de la temperatura del motor
La retención de gases calientes tan cerca del bloque motor eleva la temperatura global bajo el capó. Esto no siempre se refleja en la aguja de la temperatura del refrigerante de forma inmediata, pero somete a un estrés térmico innecesario a componentes como manguitos, sensores y juntas.

