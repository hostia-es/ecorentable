Es un aditivo concentrado con catalizadores organometálicos que reducen la **energía de activación** para la oxidación del carbono.

### Proceso de catálisis
1. **Dispersión** en el combustible.
2. **Modificación del hollín** generado.
3. **Reducción del punto de ignición** a 350-400°C (en lugar de 600°C).

## Problemas que soluciona

### 1. Saturación por conducción urbana
Permite regeneración en condiciones de carga baja.

### 2. Contaminación de inyectores
Detergentes que mantienen los cabezales limpios.

### 3. Contrapresión de escape
Restaura el flujo original.

