## ¿Qué es la EGR?
Una válvula que reintroduce un porcentaje de gases de escape al colector de admisión, bajando la temperatura de combustión y reduciendo NOx. Existen EGR neumáticas, eléctricas y refrigeradas.

## Síntomas de fallo
1. **Pérdida de potencia** y tirones.
2. **Humo negro** en aceleraciones.
3. **Aumento de consumo** del 10-15%.
4. **Testigo de avería motor** (P0401, P0402).
5. **Ralentí inestable** y vibraciones.
6. **Modo emergencia** (limp mode).
7. **Olor a gasoil** sin quemar.

## Causas de obstrucción
- Conducción urbana (no alcanza temperatura).
- Aceite degradado.
- Filtro de aire sucio.
- Inyectores con mala atomización.

## Cómo limpiar la EGR

### Opción 1: Descarbonización por hidrógeno (recomendada)
Las máquinas **H2 Profit 1000, 2000, 3000** y **Hy-Carbon Connect** de Ecología Rentable inyectan oxihidrógeno por la admisión. La pirólisis controlada limpia la EGR sin desmontarla, en 60-90 minutos. La **Hy-Carbon Connect** además se conecta al OBD para optimizar el flujo y emitir informe.

### Opción 2: Desmontaje y limpieza manual
